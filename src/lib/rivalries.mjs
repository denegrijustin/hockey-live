const index = new Map(RIVALRIES.map(r => [r.id, r]));
export function rivalryForTeams(home, away) {
  if (typeof home !== "string" || typeof away !== "string" || home === away) return null;
  return index.get([home.toUpperCase(),away.toUpperCase()].sort().join("-")) ?? null;
}
export function rivalryForGame(game) {
  return rivalryForTeams(game?.home,game?.away);
}
/** Count only final games present in loaded snapshots, before the viewed game.
 * This is NOT an all-time record and must never be labeled as such. */
export function recentHeadToHead(games, viewedGame, limit=5) {
  if (!Array.isArray(games) || !viewedGame || !Number.isInteger(limit) || limit < 1) return [];
  return games.filter(g => g && g.id !== viewedGame.id && g.start && g.start < viewedGame.start &&
    ((g.home===viewedGame.home && g.away===viewedGame.away) || (g.away===viewedGame.home && g.home===viewedGame.away)) &&
    g.homeScore != null && g.awayScore != null && ["OFF","FINAL"].includes(g.state))
    .sort((a,b)=>b.start.localeCompare(a.start)).slice(0,limit);
}
export function verifiedAllTime(record) {
  if (!record || record.validation_status!=="verified" || record.display_allowed!==true) return null;
  const keys=["wins","losses","ties","overtime_losses","games"];
  if (!keys.every(k=>Number.isInteger(record[k]) && record[k]>=0)) return null;
  if (record.wins+record.losses+record.ties+record.overtime_losses!==record.games) return null;
  return record;
}
